function balancedArray(source, start) {
  let depth = 0
  let quote = ''
  let escaped = false
  for (let index = start; index < source.length; index += 1) {
    const char = source[index]
    if (quote) {
      if (escaped) escaped = false
      else if (char === '\\') escaped = true
      else if (char === quote) quote = ''
      continue
    }
    if (char === "'" || char === '"' || char === '`') {
      quote = char
      continue
    }
    if (char === '[') depth += 1
    if (char === ']') {
      depth -= 1
      if (depth === 0) return source.slice(start, index + 1)
    }
  }
  throw new Error(`Unclosed FAQ array near byte ${start}`)
}

function findArray(source, symbol) {
  const marker = symbol
    ? new RegExp(`(?:export\\s+)?const\\s+${symbol}\\s*=\\s*\\[`)
    : /faqs=\{\s*\[/
  const match = marker.exec(source)
  if (!match) throw new Error(`FAQ array ${symbol || 'attribute'} not found`)
  return balancedArray(source, source.indexOf('[', match.index))
}

function claimKey(expression) {
  if (
    ts.isPropertyAccessExpression(expression) &&
    ts.isIdentifier(expression.expression) &&
    expression.expression.text === 'CLAIM_TEXT'
  ) {
    return expression.name.text
  }
  if (
    ts.isCallExpression(expression) &&
    ts.isIdentifier(expression.expression) &&
    ['homeClaim', 'getClaimText'].includes(expression.expression.text) &&
    expression.arguments.length >= 1 &&
    ts.isStringLiteral(expression.arguments[0])
  ) {
    return expression.arguments[0].text
  }
  throw new Error(`Unsupported FAQ template expression: ${expression.getText()}`)
}

function textValue(node) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text
  if (ts.isTemplateExpression(node)) {
    return node.templateSpans.reduce(
      (value, span) => `${value}{{${claimKey(span.expression)}}}${span.literal.text}`,
      node.head.text
    )
  }
  throw new Error(`Unsupported FAQ value: ${node.getText()}`)
}

function parseFaqs(arraySource, file) {
  const parsed = ts.createSourceFile(file, `const value = ${arraySource}`, ts.ScriptTarget.Latest)
  const statement = parsed.statements[0]
  const array = statement?.declarationList?.declarations?.[0]?.initializer
  if (!array || !ts.isArrayLiteralExpression(array)) throw new Error(`Invalid FAQ array in ${file}`)
  return array.elements.map((element) => {
    if (!ts.isObjectLiteralExpression(element)) throw new Error(`Invalid FAQ item in ${file}`)
    const values = Object.fromEntries(
      element.properties.map((property) => [
        property.name.getText(parsed),
        textValue(property.initializer),
      ])
    )
    if (!values.contentKey || !values.q || !values.a) {
      throw new Error(`FAQ item missing explicit contentKey/q/a in ${file}`)
    }
    return { contentKey: values.contentKey, question: values.q, answer: values.a }
  })
}

const seeds = sources.flatMap(([pageKey, file, symbol]) => {
  const source = readFileSync(resolve(root, file), 'utf8')
  return parseFaqs(findArray(source, symbol), file).map((faq, index) => ({
    status: 'published',
    content_key: faq.contentKey,
    faqPageKey: pageKey,
    page_key: pageKey,
    sort: index + 1,
    question: faq.question,
    answer: faq.answer,
  }))
})

assertKnownClaimReferences(seeds, { root, source: 'generate-faq-seeds' })

const output = `// Generated by scripts/generate-faq-seeds.mjs. Do not edit manually.\nexport const APPROVED_FAQ_SEEDS = ${JSON.stringify(seeds, null, 2)}\n`
const outputPath = resolve(root, 'scripts/data/approved-faq-seeds.mjs')
const prettierConfig = (await resolveConfig(outputPath)) ?? {}
writeFileSync(
  outputPath,
  await format(output, { ...prettierConfig, parser: 'babel', filepath: outputPath })
)
console.log(`Generated ${seeds.length} FAQ seeds across ${sources.length} pages.`)
