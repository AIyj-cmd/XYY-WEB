export function collectionTranslations(collection) {
  const label = CMS_COLLECTION_LABELS[collection]
  return label ? zh(label) : undefined
}

export function fieldTranslations(collection, field) {
  const label = FIELD_OVERRIDES[`${collection}.${field}`] ?? FIELD_LABELS[field]
  return label ? zh(label) : undefined
}
